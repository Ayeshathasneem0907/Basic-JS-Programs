let num1 = 4;
let num2 = 5;
let operator = "+";

switch(operator)
{
    case "+":
        console.log(num1 + num2);
        break;
    
    case "-":
        console.log(num2 - num1);
        break;
    
    case "*":
        console.log(num1 * num2);
        break;

    case "/":
        console.log(num1 / 2);
        break;
}